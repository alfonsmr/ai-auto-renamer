def _to_slug(text: str, sep: str) -> str:
    slug = re.sub(r"[^a-zA-Z0-9]+", sep, text.lower()).strip(sep)
    return slug or "document"


def format_new_filename(
    date_val: Optional[str],
    title_val: str,
    original_suffix: str,
    max_stem_chars: int = CONFIG.max_filename_stem_chars,
    naming_style: str = "date_title_case",
) -> str:
    """Format and sanitize the new filename according to macOS conventions and naming_style."""
    title = title_val.strip()
    if len(title) >= 2 and title[0] == title[-1] and title[0] in ("\"", "'", "`"):
        title = title[1:-1].strip()

    if original_suffix and title.lower().endswith(original_suffix.lower()):
        title = title[: -len(original_suffix)].strip()

    title = re.sub(r"[/\\:|]+", " - ", title)
    title = re.sub(r"[\x00-\x1f\x7f]+", " ", title)
    title = re.sub(r"\s+", " ", title).strip(" .-_")

    if not title:
        raise ValueError("Generated title is empty after sanitization.")

    valid_date: Optional[str] = normalize_date_string(date_val)

    if valid_date:
        compact_date = valid_date.replace("-", "")
        if title.startswith(valid_date):
            title = re.sub(rf"^{re.escape(valid_date)}\s*[-_:]?\s*", "", title).strip()
        elif title.startswith(compact_date):
            title = re.sub(rf"^{re.escape(compact_date)}(?:\s+\d{{4}})?\s*[-_:]?\s*", "", title).strip()

    if naming_style == "title_case":
        stem = title
    elif naming_style == "date_kebab_case":
        slug = _to_slug(title, "-")
        stem = f"{valid_date}-{slug}" if valid_date else slug
    elif naming_style == "kebab_case":
        stem = _to_slug(title, "-")
    elif naming_style == "snake_case":
        stem = _to_slug(title, "_")
    else:  # "date_title_case" (default)
        if valid_date and title:
            stem = f"{valid_date} - {title}"
        elif valid_date:
            stem = valid_date
        else:
            stem = title

    if len(stem) > max_stem_chars:
        stem = stem[:max_stem_chars].rstrip(" .-_")

    return f"{stem}{original_suffix}"


def rename_file_safely(file_path: Path, desired_filename: str) -> Path:
    """Rename file_path in place without overwriting any existing file."""
    parent = file_path.parent
    target_path = parent / desired_filename

    if file_path.name == desired_filename:
        return file_path

    if target_path.exists():
        try:
            if os.path.samefile(file_path, target_path):
                file_path.rename(target_path)
                return target_path
        except OSError:
            pass

    suffix = file_path.suffix
    stem = desired_filename[: -len(suffix)] if suffix and desired_filename.endswith(suffix) else desired_filename
    counter = 2
    while target_path.exists():
        candidate_name = f"{stem} ({counter}){suffix}"
        target_path = parent / candidate_name
        counter += 1

    file_path.rename(target_path)
    return target_path


def process_file(
    file_path: Path,
    model: Optional[str] = None,
    host: Optional[str] = None,
    trusted_provenance: Optional[Iterable[str]] = None,
    dry_run: bool = False,
    quiet: bool = False,
    config: AppConfig = CONFIG,
) -> tuple[Path, list[str]]:
    """Process a single file: load, classify via Ollama, validate, rename in place, apply tags, and notify."""
    original_name = file_path.name
    chosen_model = model or config.ollama_model
    chosen_host = host or config.ollama_host

    doc = load_document_direct(file_path, config=config)

    if not quiet:
        notify("Smart Rename", f"Analyzing '{original_name}' with {chosen_model}...")

    classification = classify_document(
        doc,
        original_filename=original_name,
        model=chosen_model,
        host=chosen_host,
        trusted_provenance=trusted_provenance,
        config=config,
    )
    new_filename = format_new_filename(
        classification.date,
        classification.title,
        file_path.suffix,
        max_stem_chars=config.max_filename_stem_chars,
        naming_style=config.naming_style,
    )

    if dry_run:
        return file_path.parent / new_filename, classification.tags

    new_path = rename_file_safely(file_path, new_filename)
    if config.enable_tagging:
        apply_finder_tags(new_path, classification.tags, config=config)

    if not quiet:
        tag_summary = (
            f" • Tags: {', '.join(classification.tags)}"
            if (config.enable_tagging and classification.tags)
            else ""
        )
        if new_path.name == original_name:
            notify(
                "Smart Rename",
                f"Kept '{original_name}'{tag_summary}",
                subtitle="Document Tagged" if config.enable_tagging else "Document Analyzed",
            )
        else:
            notify(
                "Smart Rename",
                f"{original_name} → {new_path.name}{tag_summary}",
                subtitle="Document Renamed & Tagged" if config.enable_tagging else "Document Renamed",
            )

    return new_path, classification.tags


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="AI Auto Renamer (Smart Rename) — Rename and tag documents in place using local Ollama."
    )
    parser.add_argument(
        "files",
        nargs="*",
        help="Paths to the document files to rename and tag.",
    )
    parser.add_argument(
        "--sync-tags",
        action="store_true",
        help="Synchronize configured tags and colors into macOS Finder's Tag Database and sidebar.",
    )
    parser.add_argument(
        "--config-dir",
        type=Path,
        default=None,
        help=f"Path to configuration directory (default: {DEFAULT_CONFIG_DIR}).",
    )
    parser.add_argument(
        "--model",
        default=None,
        help=f"Ollama model name (default from config/settings.json: {CONFIG.ollama_model}).",
    )
    parser.add_argument(
        "--host",
        default=None,
        help=f"Ollama server URL (default from config/settings.json: {CONFIG.ollama_host}).",
    )
    parser.add_argument(
        "--provenance",
        action="append",
        default=[],
        help=(
            "Trusted provenance relationship tag(s) supported by verified application "
            "context (e.g., received, sent, self-created). May be specified multiple times."
        ),
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print the proposed new filename and tags without modifying the file.",
    )
    parser.add_argument(
        "--no-notify",
        action="store_true",
        help="Disable macOS Notification Center banners.",
    )

    args = parser.parse_args(argv)
    if not args.files and not args.sync_tags:
        parser.error("the following arguments are required: files (or --sync-tags)")

    try:
        active_config = load_config(args.config_dir) if args.config_dir else CONFIG
    except ConfigurationError as exc:
        print(f"Configuration error: {exc}", file=sys.stderr)
        return 1

    if args.sync_tags:
        sync_finder_tag_database(active_config, force=True)
        if not args.files:
            return 0

    exit_code = 0

    for raw_path in args.files:
        file_path = Path(raw_path).expanduser().resolve()
        try:
            result_path, tags = process_file(
                file_path,
                model=args.model,
                host=args.host,
                trusted_provenance=args.provenance,
                dry_run=args.dry_run,
                quiet=args.no_notify,
                config=active_config,
            )
            tags_str = json.dumps(tags)
            if args.dry_run:
                print(f"[DRY RUN] {file_path.name} -> {result_path.name} | tags={tags_str}")
            else:
                print(f"{file_path.name} -> {result_path.name} | tags={tags_str}")
        except UnsupportedDocumentError as exc:
            print(f"Skipping {file_path.name}: {exc}", file=sys.stderr)
            if not args.no_notify:
                notify("Smart Rename — Unsupported File", str(exc))
            exit_code = 1
        except TagValidationError as exc:
            print(f"Rejected invalid tags for {file_path.name}: {exc}", file=sys.stderr)
            if not args.no_notify:
                notify("Smart Rename — Invalid Tags Rejected", str(exc))
            exit_code = 1
        except OllamaAPIError as exc:
            print(f"Ollama error for {file_path.name}: {exc}", file=sys.stderr)
            if not args.no_notify:
                notify("Smart Rename — Error", str(exc))
            exit_code = 1
        except Exception as exc:
            print(f"Unexpected error for {file_path.name}: {exc}", file=sys.stderr)
            if not args.no_notify:
                notify("Smart Rename — Error", f"Failed to process '{file_path.name}': {exc}")
            exit_code = 1

    return exit_code


if __name__ == "__main__":
    sys.exit(main())
