def notify(title: str, message: str, subtitle: str = "") -> None:
    """Display a native macOS Notification Center banner via osascript."""
    def _clean(val: str) -> str:
        return val.replace("\r", " ").replace("\n", " ").strip()

    if subtitle:
        script = (
            "on run argv\n"
            "  display notification (item 2 of argv) with title (item 1 of argv) subtitle (item 3 of argv)\n"
            "end run"
        )
        cmd = ["/usr/bin/osascript", "-e", script, _clean(title), _clean(message), _clean(subtitle)]
    else:
        script = (
            "on run argv\n"
            "  display notification (item 2 of argv) with title (item 1 of argv)\n"
            "end run"
        )
        cmd = ["/usr/bin/osascript", "-e", script, _clean(title), _clean(message)]

    try:
        subprocess.run(
            cmd,
            check=False,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            timeout=5,
        )
    except Exception:
        pass


def _find_binary(name: str) -> Optional[str]:
    """Locate a CLI tool across standard macOS and Homebrew paths (even inside Automator)."""
    for candidate in (
        f"/opt/homebrew/bin/{name}",
        f"/usr/local/bin/{name}",
        f"/usr/bin/{name}",
        f"/bin/{name}",
    ):
        if os.path.isfile(candidate) and os.access(candidate, os.X_OK):
            return candidate
    return shutil.which(name)


def _local_name(tag: str) -> str:
    """Strip XML namespace from an ElementTree tag name."""
    if "}" in tag:
        return tag.split("}", 1)[1]
    return tag


class _HTMLTextExtractor(HTMLParser):
    """Lightweight HTML/XHTML to plain text extractor for EPUB chapters."""

    _BLOCK_TAGS = {
        "p", "div", "section", "article", "header", "footer", "aside",
        "h1", "h2", "h3", "h4", "h5", "h6", "li", "tr", "br", "hr", "blockquote",
    }

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self._chunks: list[str] = []
        self._skip_depth = 0

    def handle_starttag(self, tag: str, attrs: list[tuple[str, Optional[str]]]) -> None:
        t = tag.lower()
        if t in ("script", "style", "head", "svg", "math"):
            self._skip_depth += 1
        elif self._skip_depth == 0 and t in self._BLOCK_TAGS:
            self._chunks.append("\n")

    def handle_endtag(self, tag: str) -> None:
        t = tag.lower()
        if t in ("script", "style", "head", "svg", "math") and self._skip_depth > 0:
            self._skip_depth -= 1
        elif self._skip_depth == 0 and t in self._BLOCK_TAGS:
            self._chunks.append("\n")

    def handle_data(self, data: str) -> None:
        if self._skip_depth == 0 and data:
            self._chunks.append(data)

    def get_text(self) -> str:
        raw = "".join(self._chunks)
        lines = [re.sub(r"[ \t]+", " ", line).strip() for line in raw.splitlines()]
        return "\n".join(line for line in lines if line)


def _html_to_text(html_str: str) -> str:
    parser = _HTMLTextExtractor()
    parser.feed(html_str)
    parser.close()
    return parser.get_text()


