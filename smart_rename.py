def validate_tags(
    raw_tags: Any,
    trusted_provenance: Optional[Iterable[str]] = None,
    config: AppConfig = CONFIG,
) -> list[str]:
    """Validate the LLM's proposed tags against all vocabulary, count, and provenance rules."""
    if not isinstance(raw_tags, list):
        raise TagValidationError(
            f"Expected 'tags' to be a JSON array of strings, got {type(raw_tags).__name__}."
        )

    if not config.enable_tagging:
        return []

    provenance_set = set(trusted_provenance or ())
    unknown_provenance = provenance_set - set(config.relationship_tags.keys())
    if unknown_provenance:
        raise TagValidationError(
            f"Invalid trusted provenance values supplied: {sorted(unknown_provenance)}"
        )

    approved = config.all_approved_tags
    seen: set[str] = set()
    context_count = 0
    doc_type_count = 0

    for item in raw_tags:
        if not isinstance(item, str):
            raise TagValidationError(
                f"Tag entry must be a string, got {type(item).__name__}: {item!r}"
            )
        if item not in approved:
            raise TagValidationError(
                f"Unapproved tag {item!r}. Tags must exactly match the approved vocabulary."
            )
        if item in seen:
            raise TagValidationError(f"Duplicate tag {item!r} in response.")
        seen.add(item)

        if item in config.context_tags:
            context_count += 1
        elif item in config.document_type_tags:
            doc_type_count += 1
        elif item in config.relationship_tags:
            if item not in provenance_set:
                raise TagValidationError(
                    f"Relationship tag {item!r} requires trusted provenance, "
                    f"but provenance was {sorted(provenance_set) or 'none'}."
                )

    if context_count > config.max_context_tags:
        raise TagValidationError(
            f"Too many context tags ({context_count}); maximum allowed is {config.max_context_tags}."
        )

    if doc_type_count > config.max_document_type_tags:
        raise TagValidationError(
            f"Too many document-type/purpose tags ({doc_type_count}); "
            f"maximum allowed is {config.max_document_type_tags}."
        )

    if len(raw_tags) > config.max_total_tags:
        raise TagValidationError(
            f"Too many total tags ({len(raw_tags)}); maximum allowed is {config.max_total_tags}."
        )

    return list(raw_tags)


