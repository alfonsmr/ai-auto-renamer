def normalize_date_string(raw_date: Optional[str]) -> Optional[str]:
    """Normalize common date strings returned by LLMs or found in headers into YYYY-MM-DD."""
    if not raw_date or not isinstance(raw_date, str):
        return None
    s = raw_date.strip()
    if s.lower() in ("", "null", "none", "n/a", "unknown"):
        return None
    if DATE_REGEX.match(s):
        return s

    # YYYY-M-D, YYYY/MM/DD, YYYY.MM.DD (with optional trailing timestamp)
    m = re.match(r"^((?:19|20)\d{2})[-/.](\d{1,2})[-/.](\d{1,2})\b", s)
    if m:
        year, month, day = int(m.group(1)), int(m.group(2)), int(m.group(3))
        if 1 <= month <= 12 and 1 <= day <= 31:
            return f"{year:04d}-{month:02d}-{day:02d}"

    # Compact 8-digit YYYYMMDD (e.g. 20261020)
    m = re.match(r"^((?:19|20)\d{2})(0[1-9]|1[0-2])(0[1-9]|[12]\d|3[01])\b", s)
    if m:
        return f"{m.group(1)}-{m.group(2)}-{m.group(3)}"

    # Month DD, YYYY (e.g. "October 20, 2026" or "Oct 20, 2026")
    m = re.match(r"^([A-Za-z]+)\.?\s+(\d{1,2})(?:st|nd|rd|th)?,?\s+((?:19|20)\d{2})\b", s)
    if m:
        month = _MONTH_MAP.get(m.group(1).lower())
        day = int(m.group(2))
        year = int(m.group(3))
        if month and 1 <= day <= 31:
            return f"{year:04d}-{month:02d}-{day:02d}"

    # DD Month YYYY (e.g. "20 October 2026" or "20 Oct 2026")
    m = re.match(r"^(\d{1,2})(?:st|nd|rd|th)?\s+([A-Za-z]+)\.?,?\s+((?:19|20)\d{2})\b", s)
    if m:
        day = int(m.group(1))
        month = _MONTH_MAP.get(m.group(2).lower())
        year = int(m.group(3))
        if month and 1 <= day <= 31:
            return f"{year:04d}-{month:02d}-{day:02d}"

    return None


def extract_fallback_date(original_filename: str, doc_text: str = "") -> Optional[str]:
    """Extract a clear primary date from the filename or explicit document date header when LLM returns null."""
    # 1. Check original filename for leading/embedded ISO date (YYYY-MM-DD or YYYY_MM_DD)
    m = re.search(r"\b((?:19|20)\d{2})[-_](0[1-9]|1[0-2])[-_](0[1-9]|[12]\d|3[01])\b", original_filename)
    if m:
        return f"{m.group(1)}-{m.group(2)}-{m.group(3)}"

    # 2. Check original filename for compact 8-digit YYYYMMDD (e.g. "20261020 1037 Transcription.txt")
    m = re.search(r"(?:^|\b)((?:19|20)\d{2})(0[1-9]|1[0-2])(0[1-9]|[12]\d|3[01])(?:\b|[-_\s])", original_filename)
    if m:
        return f"{m.group(1)}-{m.group(2)}-{m.group(3)}"

    if not doc_text:
        return None

    head = doc_text[:2500]
    # 3. Check explicit "Date:" / "Invoice Date:" / "Meeting Date:" / "Effective Date:" lines in document header
    for line in head.splitlines()[:40]:
        label_match = re.search(
            r"\b(?:date|dated|issued|recorded|published)\s*[:\-–]\s*(.+)$",
            line.strip(),
            flags=re.IGNORECASE,
        )
        if label_match:
            candidate = normalize_date_string(label_match.group(1).strip())
            if candidate:
                return candidate

    # 4. Check for standalone ISO date (YYYY-MM-DD) in the first 1,000 chars of document header
    m = re.search(r"\b((?:19|20)\d{2})-(0[1-9]|1[0-2])-(0[1-9]|[12]\d|3[01])\b", head[:1000])
    if m:
        return f"{m.group(1)}-{m.group(2)}-{m.group(3)}"

    # 5. Check for written date ("October 20, 2026" / "Oct 20, 2026") in the first 1,000 chars
    m = re.search(
        r"\b(Jan(?:uary)?|Feb(?:ruary)?|Mar(?:ch)?|Apr(?:il)?|May|Jun(?:e)?|Jul(?:y)?|Aug(?:ust)?|"
        r"Sep(?:t(?:ember)?)?|Oct(?:ober)?|Nov(?:ember)?|Dec(?:ember)?)\.?\s+(\d{1,2})(?:st|nd|rd|th)?,\s+((?:19|20)\d{2})\b",
        head[:1000],
        flags=re.IGNORECASE,
    )
    if m:
        month = _MONTH_MAP.get(m.group(1).lower().rstrip("."))
        day = int(m.group(2))
        year = int(m.group(3))
        if month and 1 <= day <= 31:
            return f"{year:04d}-{month:02d}-{day:02d}"

    return None


