def is_fileprovider_path(file_path: Path) -> bool:
    """Return True if file_path resides inside iCloud Drive or another macOS FileProvider domain.

    iCloud Drive (`bird` / `fileproviderd`) strips per-file `\\n<color>` suffixes from
    `com.apple.metadata:_kMDItemUserTags` and, if a non-default color suffix (`\\n2`..`\\n7`)
    was written on disk, overwrites all tags on the file with `\\n1` (Gray) and sets
    `com.apple.FinderInfo` label bits to Gray. Inside FileProvider domains, Finder instead
    resolves tag colors from the system-wide Finder Tag Database (`ProjectsItems`), so
    plain tag names (without `\\n<color>`) must be written on disk.
    """
    try:
        resolved = file_path.expanduser().resolve()
    except Exception:
        resolved = file_path.expanduser()

    parts = resolved.parts
    if "Mobile Documents" in parts or "CloudStorage" in parts:
        return True

    cur = resolved if resolved.is_dir() else resolved.parent
    for d in (cur, *cur.parents):
        try:
            pb = os.fsencode(d)
            sz = _libc.listxattr(pb, None, 0, 0)
            if sz > 0:
                buf = ctypes.create_string_buffer(sz)
                if _libc.listxattr(pb, buf, sz, 0) > 0:
                    raw_names = buf.raw[:sz]
                    if (
                        b"com.apple.file-provider-domain-id" in raw_names
                        or b"com.apple.fileprovider." in raw_names
                    ):
                        return True
        except Exception:
            continue
    return False


def sync_finder_tag_database(config: AppConfig = CONFIG, force: bool = False) -> bool:
    """Synchronize configured tags and colors into macOS Finder's Tag Database (`ProjectsItems`).

    Ensures that:
      1. All `context_tags` from `config/tags.json` are registered in Finder's Tag Database
         with their configured colors (`1..7`) and `isVisible=True` so they appear in Finder's
         left sidebar and keep their colors inside iCloud Drive.
      2. Standard macOS color tags (`Red`, `Orange`, `Yellow`, `Green`, `Blue`, `Purple`, `Gray`)
         remain registered.
      3. `document_type_tags` and `relationship_tags` are registered with `color=0` (colorless)
         and `isVisible=False` so iCloud Drive does not treat them as unregistered Gray tags.
      4. Any corrupted empty `""` entries in `com.apple.finder` `FavoriteTagNames` are removed
         and the Sidebar Tags section is disclosed.
    """
    if not config.enable_tagging:
        return False

    cfg_key = config.config_dir
    if not force and cfg_key in _SYNCED_TAG_DB_DIRS:
        return True

    try:
        objc = ctypes.CDLL("/usr/lib/libobjc.A.dylib")
        cs = ctypes.CDLL("/System/Library/Frameworks/CoreServices.framework/CoreServices")
        ctypes.CDLL("/System/Library/PrivateFrameworks/FinderKit.framework/FinderKit")
        dsp = ctypes.CDLL(
            "/System/Library/PrivateFrameworks/DesktopServicesPriv.framework/DesktopServicesPriv"
        )

        objc.objc_getClass.argtypes = [ctypes.c_char_p]
        objc.objc_getClass.restype = ctypes.c_void_p
        objc.sel_registerName.argtypes = [ctypes.c_char_p]
        objc.sel_registerName.restype = ctypes.c_void_p

        def _msg(obj: Any, sel_bytes: bytes, *args: Any, argtypes: Any = None, restype: Any = ctypes.c_void_p) -> Any:
            fn = ctypes.CFUNCTYPE(
                restype,
                ctypes.c_void_p,
                ctypes.c_void_p,
                *(argtypes or [ctypes.c_void_p] * len(args)),
            )(("objc_msgSend", objc))
            return fn(obj, objc.sel_registerName(sel_bytes), *args)

        def _nsstring(s: str) -> Any:
            return _msg(
                objc.objc_getClass(b"NSString"),
                b"stringWithUTF8String:",
                s.encode("utf-8"),
                argtypes=[ctypes.c_char_p],
            )

        def _to_str(ns_obj: Any) -> Optional[str]:
            if not ns_obj:
                return None
            desc = _msg(ns_obj, b"description")
            cstr = _msg(desc, b"UTF8String", restype=ctypes.c_char_p)
            return cstr.decode("utf-8") if cstr else None

        cs.LSSharedFileListCreate.argtypes = [ctypes.c_void_p, ctypes.c_void_p, ctypes.c_void_p]
        cs.LSSharedFileListCreate.restype = ctypes.c_void_p
        cs.LSSharedFileListCopySnapshot.argtypes = [
            ctypes.c_void_p,
            ctypes.POINTER(ctypes.c_uint32),
        ]
        cs.LSSharedFileListCopySnapshot.restype = ctypes.c_void_p
        cs.LSSharedFileListItemCopyDisplayName.argtypes = [ctypes.c_void_p]
        cs.LSSharedFileListItemCopyDisplayName.restype = ctypes.c_void_p
        cs.LSSharedFileListItemCopyProperty.argtypes = [ctypes.c_void_p, ctypes.c_void_p]
        cs.LSSharedFileListItemCopyProperty.restype = ctypes.c_void_p

        dsp._NodeSetTagDatabase.argtypes = [ctypes.c_void_p, ctypes.c_bool]
        dsp._NodeSetTagDatabase.restype = ctypes.c_int

        sfl = cs.LSSharedFileListCreate(
            None, _nsstring("com.apple.LSSharedFileList.ProjectsItems"), None
        )
        if not sfl:
            return False

        seed = ctypes.c_uint32(0)
        snap = cs.LSSharedFileListCopySnapshot(sfl, ctypes.byref(seed))
        cnt = _msg(snap, b"count", restype=ctypes.c_ulong) if snap else 0

        existing_map: dict[str, tuple[int, bool, bool]] = {}
        prop_hidden = _nsstring("com.apple.LSSharedFileList.ItemIsHidden")
        prop_label = _nsstring("kLSSharedTagFileListItemLabel")
        prop_pinned = _nsstring("kLSSharedTagFileListItemPinned")

        for i in range(cnt):
            item = _msg(snap, b"objectAtIndex:", i, argtypes=[ctypes.c_ulong])
            name = _to_str(cs.LSSharedFileListItemCopyDisplayName(item))
            if not name:
                continue
            hidden_s = _to_str(cs.LSSharedFileListItemCopyProperty(item, prop_hidden))
            label_s = _to_str(cs.LSSharedFileListItemCopyProperty(item, prop_label))
            pinned_s = _to_str(cs.LSSharedFileListItemCopyProperty(item, prop_pinned))
            is_vis = hidden_s != "1"
            is_pin = pinned_s == "1"
            try:
                col = int(label_s) if label_s else 0
            except ValueError:
                col = 0
            existing_map[name] = (col, is_vis, is_pin)

        # Check com.apple.finder FavoriteTagNames for corrupted empty strings
        NSUserDefaults = objc.objc_getClass(b"NSUserDefaults")
        finder_defs = _msg(
            _msg(NSUserDefaults, b"alloc"),
            b"initWithSuiteName:",
            _nsstring("com.apple.finder"),
        )
        fav_arr = _msg(finder_defs, b"stringArrayForKey:", _nsstring("FavoriteTagNames"))
        raw_favs: list[str] = []
        if fav_arr:
            fcnt = _msg(fav_arr, b"count", restype=ctypes.c_ulong)
            for i in range(fcnt):
                val = _to_str(_msg(fav_arr, b"objectAtIndex:", i, argtypes=[ctypes.c_ulong]))
                raw_favs.append(val or "")

        clean_favs = [f.strip() for f in raw_favs if f and f.strip()]
        favs_corrupted = clean_favs != raw_favs

        # Check if all configured context tags & document-type tags are already synced
        if not force and not favs_corrupted and cnt > 0:
            all_synced = True
            for c_tag in config.context_tags:
                expected_col = config.tag_colors.get(c_tag, 0)
                cur_entry = existing_map.get(c_tag)
                if cur_entry is None or cur_entry[0] != expected_col or not cur_entry[1]:
                    all_synced = False
                    break
            if all_synced:
                for d_tag in (*config.document_type_tags.keys(), *config.relationship_tags.keys()):
                    if d_tag not in existing_map:
                        all_synced = False
                        break
            if all_synced:
                _SYNCED_TAG_DB_DIRS.add(cfg_key)
                return True

        NSMutableArray = objc.objc_getClass(b"NSMutableArray")
        if favs_corrupted and finder_defs:
            clean_fav_ns = _msg(NSMutableArray, b"array")
            for fn in clean_favs:
                _msg(clean_fav_ns, b"addObject:", _nsstring(fn))
            _msg(finder_defs, b"setObject:forKey:", clean_fav_ns, _nsstring("FavoriteTagNames"))

        if finder_defs:
            _msg(
                finder_defs,
                b"setBool:forKey:",
                True,
                _nsstring("SidebarTagsSctionDisclosedState"),
                argtypes=[ctypes.c_bool, ctypes.c_void_p],
            )
            _msg(
                finder_defs,
                b"setBool:forKey:",
                True,
                _nsstring("ShowRecentTags"),
                argtypes=[ctypes.c_bool, ctypes.c_void_p],
            )
            _msg(finder_defs, b"synchronize", restype=ctypes.c_bool)

        fav_set = set(clean_favs)
        desired_tags: dict[str, tuple[int, bool, bool]] = {}

        # 1. Context tags (colored 1..7, visible in Finder left sidebar)
        for tag_name in config.context_tags:
            color_code = config.tag_colors.get(tag_name, 0)
            desired_tags[tag_name] = (color_code, True, tag_name in fav_set)

        # 2. Standard macOS color tags
        for std_name, std_color in STANDARD_MACOS_COLOR_TAGS:
            if std_name not in desired_tags:
                prev = existing_map.get(std_name)
                is_vis = prev[1] if prev is not None else True
                desired_tags[std_name] = (std_color, is_vis, std_name in fav_set)

        # 3. Document-type and relationship tags (color = 0, hidden from sidebar unless favorite)
        for tag_name in (*config.document_type_tags.keys(), *config.relationship_tags.keys()):
            if tag_name not in desired_tags:
                color_code = config.tag_colors.get(tag_name, 0)
                is_vis = tag_name in fav_set
                desired_tags[tag_name] = (color_code, is_vis, tag_name in fav_set)

        # 4. Preserve any additional user tags already in ProjectsItems
        for existing_name, (ex_col, ex_vis, ex_pin) in existing_map.items():
            if existing_name not in desired_tags:
                color_code = config.tag_colors.get(existing_name, ex_col)
                desired_tags[existing_name] = (
                    color_code,
                    ex_vis,
                    (existing_name in fav_set) or ex_pin,
                )

        FITag = objc.objc_getClass(b"FITag")
        tag_dict_array = _msg(NSMutableArray, b"array")
        for t_name, (t_color, t_vis, t_pin) in desired_tags.items():
            fitag = _msg(
                _msg(FITag, b"alloc"),
                b"initWithName:color:isVisible:isPinned:",
                _nsstring(t_name),
                t_color,
                t_vis,
                t_pin,
                argtypes=[ctypes.c_void_p, ctypes.c_int16, ctypes.c_bool, ctypes.c_bool],
            )
            t_dict = _msg(fitag, b"toDictionary")
            if t_dict:
                _msg(tag_dict_array, b"addObject:", t_dict)

        dsp._NodeSetTagDatabase(tag_dict_array, True)
        dsp._NodeSetTagDatabase(tag_dict_array, False)
        _SYNCED_TAG_DB_DIRS.add(cfg_key)
        return True
    except Exception:
        return False


def read_finder_tags(file_path: Path) -> list[str]:
    """Read existing macOS Finder tags from a file's extended attributes."""
    path_bytes = os.fsencode(file_path)
    size = _libc.getxattr(path_bytes, FINDER_TAGS_XATTR, None, 0, 0, 0)
    if size < 0:
        err = ctypes.get_errno()
        if err in (ENOATTR, errno.ENODATA, errno.ENOENT):
            return []
        raise OSError(err, os.strerror(err), str(file_path))
    if size == 0:
        return []

    buf = ctypes.create_string_buffer(size)
    read_len = _libc.getxattr(path_bytes, FINDER_TAGS_XATTR, buf, size, 0, 0)
    if read_len < 0:
        err = ctypes.get_errno()
        if err in (ENOATTR, errno.ENODATA):
            return []
        raise OSError(err, os.strerror(err), str(file_path))

    try:
        parsed = plistlib.loads(buf.raw[:read_len])
    except Exception:
        return []

    if not isinstance(parsed, list):
        return []
    return [item for item in parsed if isinstance(item, str)]


def _sync_finder_info_color(path_bytes: bytes, tags: list[str]) -> None:
    """Sync the 32-byte com.apple.FinderInfo color label bits with the primary colored tag."""
    primary_color = 0
    for t in tags:
        if "\n" in t:
            try:
                c = int(t.split("\n", 1)[1].strip())
                if 1 <= c <= 7:
                    primary_color = c
                    break
            except ValueError:
                pass

    buf = ctypes.create_string_buffer(32)
    read_len = _libc.getxattr(path_bytes, FINDER_INFO_XATTR, buf, 32, 0, 0)
    if read_len == 32:
        raw = bytearray(buf.raw[:32])
        raw[9] = (raw[9] & ~0x0E) | ((primary_color & 0x07) << 1)
        _libc.setxattr(path_bytes, FINDER_INFO_XATTR, bytes(raw), 32, 0, 0)


def write_finder_tags(file_path: Path, tags: list[str]) -> None:
    """Write macOS Finder tags to a file's extended attributes as binary plist."""
    path_bytes = os.fsencode(file_path)
    data = plistlib.dumps(tags, fmt=plistlib.FMT_BINARY)
    res = _libc.setxattr(path_bytes, FINDER_TAGS_XATTR, data, len(data), 0, 0)
    if res != 0:
        err = ctypes.get_errno()
        raise OSError(err, os.strerror(err), str(file_path))
    _sync_finder_info_color(path_bytes, tags)


def _base_tag_name(raw_tag: str) -> str:
    """Extract the tag name without Finder's optional '\\n<color_id>' suffix."""
    return raw_tag.split("\n", 1)[0]


def merge_finder_tags(
    existing_tags: list[str],
    new_validated_tags: list[str],
    tag_colors: Optional[dict[str, int]] = None,
) -> list[str]:
    """Merge existing user tags with newly validated tags without duplicates.

    Preserves all existing user tags and custom colors. If an existing tag on the
    file is uncolored and `tag_colors` defines a color for it, upgrades that entry
    in place with its configured Finder color code.
    """
    merged = list(existing_tags)
    index_by_base: dict[str, int] = {}
    for idx, existing_raw in enumerate(merged):
        base_name = _base_tag_name(existing_raw)
        if base_name not in index_by_base:
            index_by_base[base_name] = idx

    colors = tag_colors if tag_colors is not None else CONFIG.tag_colors

    for tag in new_validated_tags:
        base = _base_tag_name(tag)
        color_id = colors.get(base, 0)
        formatted_tag = f"{base}\n{color_id}"

        if base not in index_by_base:
            index_by_base[base] = len(merged)
            merged.append(formatted_tag)
        else:
            existing_idx = index_by_base[base]
            # Ensure the tag conforms to the configured color schema (\n1..\n7 for
            # colored context tags, \n0 for colorless document-type tags).
            merged[existing_idx] = formatted_tag

    return merged


def apply_finder_tags(
    file_path: Path,
    validated_tags: list[str],
    config: AppConfig = CONFIG,
) -> list[str]:
    """Apply validated tags to file_path while preserving existing user tags."""
    existing = read_finder_tags(file_path)
    if not config.enable_tagging:
        return [_base_tag_name(t) for t in existing]

    sync_finder_tag_database(config)
    merged = merge_finder_tags(existing, validated_tags, tag_colors=config.tag_colors)
    if is_fileprovider_path(file_path):
        # Inside iCloud Drive / FileProvider domains, per-file \n<color> suffixes
        # cause fileproviderd/bird to overwrite all tags on disk with \n1 (Gray).
        # Plain tag names must be written so Finder resolves colors from the
        # system-wide Finder Tag Database (ProjectsItems).
        target_tags = [_base_tag_name(t) for t in merged]
    else:
        target_tags = merged

    if target_tags != existing:
        write_finder_tags(file_path, target_tags)
    return [_base_tag_name(t) for t in merged]


