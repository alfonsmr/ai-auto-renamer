def extract_pdf(file_path: Path, config: AppConfig = CONFIG) -> DocumentInput:
    """Extract text from a PDF via pdftotext, or render pages via pdftoppm if scanned."""
    pdftotext_bin = _find_binary("pdftotext")
    pdftoppm_bin = _find_binary("pdftoppm")
    pdfinfo_bin = _find_binary("pdfinfo")

    meta_lines: list[str] = []
    if pdfinfo_bin:
        try:
            proc = subprocess.run(
                [pdfinfo_bin, str(file_path)],
                capture_output=True,
                text=True,
                timeout=10,
                check=False,
            )
            if proc.returncode == 0 and proc.stdout:
                for line in proc.stdout.splitlines():
                    if line.startswith(("Title:", "Subject:", "Author:", "CreationDate:", "ModDate:")):
                        val = line.split(":", 1)[1].strip()
                        if val:
                            meta_lines.append(line.strip())
        except Exception:
            pass

    extracted_text = ""
    if pdftotext_bin:
        try:
            proc = subprocess.run(
                [
                    pdftotext_bin,
                    "-f",
                    "1",
                    "-l",
                    str(config.max_pdf_text_pages),
                    "-enc",
                    "UTF-8",
                    str(file_path),
                    "-",
                ],
                capture_output=True,
                text=True,
                timeout=20,
                check=False,
            )
            if proc.returncode == 0 and proc.stdout:
                extracted_text = proc.stdout.strip()
        except Exception:
            pass

    non_ws_chars = len(re.sub(r"\s+", "", extracted_text))
    if non_ws_chars >= config.min_pdf_text_chars:
        header = ("[PDF Metadata]\n" + "\n".join(meta_lines) + "\n\n") if meta_lines else ""
        full_text = (header + extracted_text)[: config.max_text_chars].strip()
        return DocumentInput(kind="text", content=full_text, images=[], extension=".pdf")

    # Fallback for scanned / image-only PDFs: render first pages to PNG via pdftoppm
    if pdftoppm_bin:
        try:
            with tempfile.TemporaryDirectory() as tmp_dir:
                out_prefix = str(Path(tmp_dir) / "page")
                subprocess.run(
                    [
                        pdftoppm_bin,
                        "-png",
                        "-r",
                        str(config.pdf_vision_dpi),
                        "-f",
                        "1",
                        "-l",
                        str(config.max_pdf_vision_pages),
                        str(file_path),
                        out_prefix,
                    ],
                    capture_output=True,
                    timeout=30,
                    check=True,
                )
                png_files = sorted(Path(tmp_dir).glob("page*.png"))
                if png_files:
                    b64_images = [
                        base64.b64encode(p.read_bytes()).decode("ascii")
                        for p in png_files
                    ]
                    caption_parts: list[str] = []
                    if meta_lines:
                        caption_parts.append("[PDF Metadata]\n" + "\n".join(meta_lines))
                    if extracted_text:
                        caption_parts.append("[Partial OCR Text]\n" + extracted_text)
                    return DocumentInput(
                        kind="image",
                        content="\n\n".join(caption_parts),
                        images=b64_images,
                        extension=".pdf",
                    )
        except Exception as exc:
            raise UnsupportedDocumentError(
                f"Failed to extract text or render scanned pages from '{file_path.name}': {exc}"
            ) from exc

    raise UnsupportedDocumentError(
        f"'{file_path.name}' contains no extractable text and pdftoppm is unavailable."
    )


MAX_ZIP_MEMBER_BYTES = 32 * 1024 * 1024  # 32 MB limit per archive XML/HTML member


def _read_zip_member_safely(
    zf: zipfile.ZipFile,
    member: str,
    max_bytes: int = MAX_ZIP_MEMBER_BYTES,
) -> bytes:
    """Read a ZIP archive member while enforcing an uncompressed size ceiling."""
    info = zf.getinfo(member)
    if info.file_size > max_bytes:
        raise UnsupportedDocumentError(
            f"Archive entry '{member}' exceeds maximum uncompressed size ({max_bytes} bytes)."
        )
    with zf.open(info, "r") as fp:
        data = fp.read(max_bytes + 1)
    if len(data) > max_bytes:
        raise UnsupportedDocumentError(
            f"Archive entry '{member}' exceeds maximum uncompressed size ({max_bytes} bytes)."
        )
    return data


def _extract_docx_or_odt_xml_fallback(file_path: Path) -> str:
    """Fallback XML text extractor for .docx and .odt archives."""
    ext = file_path.suffix.lower()
    target_member = "word/document.xml" if ext == ".docx" else "content.xml"
    paragraphs: list[str] = []

    try:
        with zipfile.ZipFile(file_path, "r") as zf:
            if target_member not in zf.namelist():
                return ""
            root = ET.fromstring(_read_zip_member_safely(zf, target_member))
    except Exception:
        return ""

    para_tags = {"p", "h"}
    for elem in root.iter():
        if _local_name(elem.tag) in para_tags:
            text = "".join(elem.itertext()).strip()
            if text:
                paragraphs.append(text)
    return "\n".join(paragraphs)


def extract_word_or_richtext(file_path: Path, config: AppConfig = CONFIG) -> DocumentInput:
    """Extract text from .docx, .doc, .rtf, and .odt using macOS textutil (with XML fallback)."""
    ext = file_path.suffix.lower()
    textutil_bin = _find_binary("textutil")
    extracted = ""

    if textutil_bin:
        try:
            proc = subprocess.run(
                [textutil_bin, "-convert", "txt", "-stdout", str(file_path)],
                capture_output=True,
                text=True,
                timeout=20,
                check=False,
            )
            if proc.returncode == 0 and proc.stdout:
                extracted = proc.stdout.strip()
        except Exception:
            pass

    if not extracted and ext in (".docx", ".odt"):
        extracted = _extract_docx_or_odt_xml_fallback(file_path).strip()

    if not extracted:
        raise UnsupportedDocumentError(f"Could not extract any readable text from '{file_path.name}'.")

    return DocumentInput(
        kind="text",
        content=extracted[: config.max_text_chars],
        images=[],
        extension=ext,
    )


def _col_letters_to_index(cell_ref: str) -> int:
    """Convert an Excel cell reference like 'C12' to a 0-based column index (2)."""
    letters = "".join(ch for ch in cell_ref if ch.isalpha()).upper()
    if not letters:
        return 0
    idx = 0
    for ch in letters:
        idx = idx * 26 + (ord(ch) - ord("A") + 1)
    return idx - 1


def _extract_xlsx(file_path: Path, config: AppConfig = CONFIG) -> str:
    """Extract sheet names and cell rows from an Excel .xlsx archive."""
    try:
        with zipfile.ZipFile(file_path, "r") as zf:
            names = set(zf.namelist())

            shared_strings: list[str] = []
            if "xl/sharedStrings.xml" in names:
                ss_root = ET.fromstring(_read_zip_member_safely(zf, "xl/sharedStrings.xml"))
                for si in ss_root:
                    if _local_name(si.tag) == "si":
                        text_parts = [
                            t.text or ""
                            for t in si.iter()
                            if _local_name(t.tag) == "t"
                        ]
                        shared_strings.append("".join(text_parts))

            rel_map: dict[str, str] = {}
            if "xl/_rels/workbook.xml.rels" in names:
                rels_root = ET.fromstring(_read_zip_member_safely(zf, "xl/_rels/workbook.xml.rels"))
                for rel in rels_root:
                    if _local_name(rel.tag) == "Relationship":
                        r_id = rel.attrib.get("Id", "")
                        target = rel.attrib.get("Target", "")
                        if r_id and target:
                            norm = str(PurePosixPath("xl") / target.lstrip("/")) if not target.startswith("xl/") else target
                            rel_map[r_id] = norm

            sheets: list[tuple[str, str]] = []
            if "xl/workbook.xml" in names:
                wb_root = ET.fromstring(_read_zip_member_safely(zf, "xl/workbook.xml"))
                for elem in wb_root.iter():
                    if _local_name(elem.tag) == "sheet":
                        sheet_name = elem.attrib.get("name", "Sheet")
                        r_id = ""
                        for k, v in elem.attrib.items():
                            if k.endswith("}id") or k == "r:id":
                                r_id = v
                                break
                        target_path = rel_map.get(r_id, "")
                        if target_path in names:
                            sheets.append((sheet_name, target_path))

            if not sheets:
                for candidate in sorted(n for n in names if n.startswith("xl/worksheets/sheet") and n.endswith(".xml")):
                    sheets.append((PurePosixPath(candidate).stem, candidate))

            sections: list[str] = []
            for sheet_name, sheet_path in sheets[: config.max_spreadsheet_sheets]:
                ws_root = ET.fromstring(_read_zip_member_safely(zf, sheet_path))
                rows_out: list[str] = []
                for row_elem in ws_root.iter():
                    if _local_name(row_elem.tag) != "row":
                        continue
                    row_cells: dict[int, str] = {}
                    next_col = 0
                    for cell in row_elem:
                        if _local_name(cell.tag) != "c":
                            continue
                        ref = cell.attrib.get("r", "")
                        col_idx = _col_letters_to_index(ref) if ref else next_col
                        next_col = col_idx + 1
                        cell_type = cell.attrib.get("t", "")

                        val_str = ""
                        if cell_type == "inlineStr":
                            val_str = "".join(
                                t.text or ""
                                for t in cell.iter()
                                if _local_name(t.tag) == "t"
                            )
                        else:
                            v_elem = next((ch for ch in cell if _local_name(ch.tag) == "v"), None)
                            if v_elem is not None and v_elem.text is not None:
                                raw_v = v_elem.text.strip()
                                if cell_type == "s":
                                    try:
                                        ss_idx = int(raw_v)
                                        if 0 <= ss_idx < len(shared_strings):
                                            val_str = shared_strings[ss_idx]
                                    except ValueError:
                                        val_str = raw_v
                                elif cell_type == "b":
                                    val_str = "TRUE" if raw_v == "1" else "FALSE"
                                else:
                                    val_str = raw_v
                        val_str = re.sub(r"\s+", " ", val_str).strip()
                        if val_str:
                            row_cells[col_idx] = val_str

                    if row_cells:
                        max_c = min(max(row_cells.keys()), 25)
                        ordered = [row_cells.get(i, "") for i in range(max_c + 1)]
                        rows_out.append(" | ".join(ordered).rstrip(" |"))
                        if len(rows_out) >= config.max_spreadsheet_rows_per_sheet:
                            break

                if rows_out:
                    sections.append(f"[Sheet: {sheet_name}]\n" + "\n".join(rows_out))

            return "\n\n".join(sections)
    except zipfile.BadZipFile as exc:
        raise UnsupportedDocumentError(f"'{file_path.name}' is not a valid .xlsx archive.") from exc


def _extract_ods(file_path: Path, config: AppConfig = CONFIG) -> str:
    """Extract sheet names and cell rows from an OpenDocument Spreadsheet (.ods)."""
    try:
        with zipfile.ZipFile(file_path, "r") as zf:
            if "content.xml" not in zf.namelist():
                raise UnsupportedDocumentError(f"'{file_path.name}' is missing content.xml.")
            root = ET.fromstring(_read_zip_member_safely(zf, "content.xml"))
    except zipfile.BadZipFile as exc:
        raise UnsupportedDocumentError(f"'{file_path.name}' is not a valid .ods archive.") from exc

    sections: list[str] = []
    for elem in root.iter():
        if _local_name(elem.tag) != "table":
            continue
        sheet_name = next(
            (v for k, v in elem.attrib.items() if k.endswith("}name") or k == "name"),
            "Sheet",
        )
        rows_out: list[str] = []
        for child in elem:
            if _local_name(child.tag) != "table-row":
                continue
            cells: list[str] = []
            for cell in child:
                if _local_name(cell.tag) == "table-cell":
                    cell_text = " ".join(t.strip() for t in cell.itertext() if t.strip())
                    cells.append(cell_text)
            if any(cells):
                rows_out.append(" | ".join(cells).rstrip(" |"))
                if len(rows_out) >= config.max_spreadsheet_rows_per_sheet:
                    break
        if rows_out:
            sections.append(f"[Sheet: {sheet_name}]\n" + "\n".join(rows_out))
            if len(sections) >= config.max_spreadsheet_sheets:
                break
    return "\n\n".join(sections)


def extract_spreadsheet(file_path: Path, config: AppConfig = CONFIG) -> DocumentInput:
    """Extract structured table text from .xlsx and .ods spreadsheets."""
    ext = file_path.suffix.lower()
    text = _extract_xlsx(file_path, config=config) if ext == ".xlsx" else _extract_ods(file_path, config=config)
    trimmed = text[: config.max_text_chars].strip()
    if not trimmed:
        raise UnsupportedDocumentError(f"Spreadsheet '{file_path.name}' contains no readable data.")
    return DocumentInput(kind="text", content=trimmed, images=[], extension=ext)


def _slide_sort_key(member_name: str) -> int:
    m = re.search(r"(\d+)\.xml$", member_name)
    return int(m.group(1)) if m else 999999


def _extract_pptx(file_path: Path) -> str:
    """Extract slide text and speaker notes in slide order from a .pptx archive."""
    try:
        with zipfile.ZipFile(file_path, "r") as zf:
            names = set(zf.namelist())
            sections: list[str] = []

            if "docProps/core.xml" in names:
                try:
                    core_root = ET.fromstring(_read_zip_member_safely(zf, "docProps/core.xml"))
                    meta_items: list[str] = []
                    for child in core_root:
                        lname = _local_name(child.tag)
                        text_val = (child.text or "").strip()
                        if lname in ("title", "subject", "creator", "description", "created") and text_val:
                            meta_items.append(f"{lname.capitalize()}: {text_val}")
                    if meta_items:
                        sections.append("[Presentation Metadata]\n" + "\n".join(meta_items))
                except Exception:
                    pass

            slide_files = sorted(
                (n for n in names if re.match(r"^ppt/slides/slide\d+\.xml$", n)),
                key=_slide_sort_key,
            )

            for idx, slide_path in enumerate(slide_files, start=1):
                slide_root = ET.fromstring(_read_zip_member_safely(zf, slide_path))
                paragraphs: list[str] = []
                for p in slide_root.iter():
                    if _local_name(p.tag) == "p":
                        runs = [t.text or "" for t in p.iter() if _local_name(t.tag) == "t"]
                        line = "".join(runs).strip()
                        if line:
                            paragraphs.append(line)

                notes_path = f"ppt/notesSlides/notesSlide{idx}.xml"
                notes_paragraphs: list[str] = []
                if notes_path in names:
                    try:
                        notes_root = ET.fromstring(_read_zip_member_safely(zf, notes_path))
                        for p in notes_root.iter():
                            if _local_name(p.tag) == "p":
                                runs = [t.text or "" for t in p.iter() if _local_name(t.tag) == "t"]
                                line = "".join(runs).strip()
                                if line and line != str(idx):
                                    notes_paragraphs.append(line)
                    except Exception:
                        pass

                if paragraphs or notes_paragraphs:
                    block = f"[Slide {idx}]\n" + "\n".join(paragraphs)
                    if notes_paragraphs:
                        block += f"\n[Slide {idx} Notes]\n" + "\n".join(notes_paragraphs)
                    sections.append(block)

            return "\n\n".join(sections)
    except zipfile.BadZipFile as exc:
        raise UnsupportedDocumentError(f"'{file_path.name}' is not a valid .pptx archive.") from exc


def _extract_odp(file_path: Path) -> str:
    """Extract slide text in order from an OpenDocument Presentation (.odp)."""
    try:
        with zipfile.ZipFile(file_path, "r") as zf:
            if "content.xml" not in zf.namelist():
                raise UnsupportedDocumentError(f"'{file_path.name}' is missing content.xml.")
            root = ET.fromstring(_read_zip_member_safely(zf, "content.xml"))
    except zipfile.BadZipFile as exc:
        raise UnsupportedDocumentError(f"'{file_path.name}' is not a valid .odp archive.") from exc

    sections: list[str] = []
    slide_idx = 0
    for elem in root.iter():
        if _local_name(elem.tag) == "page":
            slide_idx += 1
            lines = [
                "".join(p.itertext()).strip()
                for p in elem.iter()
                if _local_name(p.tag) == "p"
            ]
            lines = [line for line in lines if line]
            if lines:
                sections.append(f"[Slide {slide_idx}]\n" + "\n".join(lines))
    return "\n\n".join(sections)


def extract_presentation(file_path: Path, config: AppConfig = CONFIG) -> DocumentInput:
    """Extract text and speaker notes from .pptx and .odp slide presentations."""
    ext = file_path.suffix.lower()
    text = _extract_pptx(file_path) if ext == ".pptx" else _extract_odp(file_path)
    trimmed = text[: config.max_text_chars].strip()
    if not trimmed:
        raise UnsupportedDocumentError(f"Presentation '{file_path.name}' contains no readable text.")
    return DocumentInput(kind="text", content=trimmed, images=[], extension=ext)


def extract_epub(file_path: Path, config: AppConfig = CONFIG) -> DocumentInput:
    """Extract Dublin Core metadata and opening chapter text from an .epub e-book."""
    try:
        with zipfile.ZipFile(file_path, "r") as zf:
            names = set(zf.namelist())
            opf_path = ""

            if "META-INF/container.xml" in names:
                try:
                    c_root = ET.fromstring(_read_zip_member_safely(zf, "META-INF/container.xml"))
                    for elem in c_root.iter():
                        if _local_name(elem.tag) == "rootfile":
                            candidate = elem.attrib.get("full-path", "")
                            if candidate in names:
                                opf_path = candidate
                                break
                except Exception:
                    pass

            if not opf_path:
                opf_candidates = [n for n in names if n.lower().endswith(".opf")]
                if opf_candidates:
                    opf_path = opf_candidates[0]

            if not opf_path:
                raise UnsupportedDocumentError(f"'{file_path.name}' is missing an EPUB OPF manifest.")

            opf_root = ET.fromstring(_read_zip_member_safely(zf, opf_path))
            opf_dir = PurePosixPath(opf_path).parent

            meta_lines: list[str] = []
            wanted_dc = {"title", "creator", "date", "publisher", "subject", "description", "language"}
            for elem in opf_root.iter():
                lname = _local_name(elem.tag).lower()
                text_val = (elem.text or "").strip()
                if lname in wanted_dc and text_val:
                    val = re.sub(r"\s+", " ", text_val)
                    meta_lines.append(f"{lname.capitalize()}: {val}")

            manifest_map: dict[str, str] = {}
            for elem in opf_root.iter():
                if _local_name(elem.tag) == "item":
                    item_id = elem.attrib.get("id", "")
                    href = elem.attrib.get("href", "")
                    media_type = elem.attrib.get("media-type", "")
                    if item_id and href and ("html" in media_type or href.lower().endswith((".xhtml", ".html", ".htm"))):
                        resolved = str(opf_dir / href) if str(opf_dir) != "." else href
                        manifest_map[item_id] = resolved

            spine_paths: list[str] = []
            for elem in opf_root.iter():
                if _local_name(elem.tag) == "itemref":
                    idref = elem.attrib.get("idref", "")
                    if idref in manifest_map:
                        spine_paths.append(manifest_map[idref])

            if not spine_paths:
                spine_paths = list(manifest_map.values())

            chapter_texts: list[str] = []
            collected_chars = 0
            for ch_path in spine_paths[: config.max_epub_chapters]:
                if ch_path not in names:
                    continue
                try:
                    raw_html = _read_zip_member_safely(zf, ch_path).decode("utf-8", errors="replace")
                    ch_text = _html_to_text(raw_html).strip()
                    if ch_text:
                        chapter_texts.append(ch_text)
                        collected_chars += len(ch_text)
                        if collected_chars >= config.max_text_chars:
                            break
                except Exception:
                    continue

            sections: list[str] = []
            if meta_lines:
                sections.append("[EPUB Metadata]\n" + "\n".join(meta_lines))
            if chapter_texts:
                sections.append("[EPUB Content]\n" + "\n\n".join(chapter_texts))

            combined = "\n\n".join(sections)[: config.max_text_chars].strip()
            if not combined:
                raise UnsupportedDocumentError(f"EPUB '{file_path.name}' contains no readable metadata or text.")

            return DocumentInput(kind="text", content=combined, images=[], extension=".epub")
    except zipfile.BadZipFile as exc:
        raise UnsupportedDocumentError(f"'{file_path.name}' is not a valid .epub archive.") from exc


def load_document_direct(file_path: Path, config: AppConfig = CONFIG) -> DocumentInput:
    """Load or extract a document so it can be classified by Ollama + Gemma 4."""
    if not file_path.exists():
        raise UnsupportedDocumentError(f"File not found: '{file_path.name}'")
    if file_path.is_dir():
        raise UnsupportedDocumentError(f"'{file_path.name}' is a folder or bundle, not a single document.")

    ext = file_path.suffix.lower()

    if ext in config.known_unsupported_binary_extensions:
        raise UnsupportedDocumentError(
            f"'{file_path.name}' ({ext}) is an unsupported binary format."
        )

    file_size = file_path.stat().st_size
    if file_size == 0:
        raise UnsupportedDocumentError(f"'{file_path.name}' is empty.")

    # 1. Native image formats
    if ext in config.supported_image_extensions:
        if file_size > config.max_image_bytes:
            raise UnsupportedDocumentError(f"'{file_path.name}' exceeds the image size limit.")
        raw_bytes = file_path.read_bytes()
        b64_image = base64.b64encode(raw_bytes).decode("ascii")
        return DocumentInput(kind="image", content="", images=[b64_image], extension=ext)

    # 2. Local conversion formats: PDF, Word/RichText, Spreadsheets, Presentations, EPUB
    if ext in config.pdf_extensions:
        return extract_pdf(file_path, config=config)
    if ext in config.word_and_richtext_extensions:
        return extract_word_or_richtext(file_path, config=config)
    if ext in config.spreadsheet_extensions:
        return extract_spreadsheet(file_path, config=config)
    if ext in config.presentation_extensions:
        return extract_presentation(file_path, config=config)
    if ext in config.epub_extensions:
        return extract_epub(file_path, config=config)

    # 3. Direct UTF-8 text documents
    if not config.enable_direct_text:
        raise UnsupportedDocumentError(
            f"'{file_path.name}' ({ext or 'text'}) is not enabled in config/settings.json."
        )

    with file_path.open("rb") as f:
        raw_chunk = f.read(config.max_text_bytes)

    if b"\x00" in raw_chunk:
        raise UnsupportedDocumentError(
            f"'{file_path.name}' is a binary file and cannot be sent directly to Ollama as text."
        )

    try:
        text = raw_chunk.decode("utf-8-sig")
    except UnicodeDecodeError as exc:
        raise UnsupportedDocumentError(
            f"'{file_path.name}' is not UTF-8 encoded text and cannot be sent directly to Ollama."
        ) from exc

    trimmed = text[: config.max_text_chars].strip()
    if not trimmed:
        raise UnsupportedDocumentError(f"'{file_path.name}' contains only whitespace.")

    return DocumentInput(kind="text", content=trimmed, images=[], extension=ext)


